def load_systems():
    """Add every other system RetroArch can run to CORES.

    system/systems.tsv is generated by install/gen-systems.py from the core
    .info files and the databases, so a game dropped into any of the folders
    install.sh creates gets the right core without anyone editing this script.
    The deliberate choices above are left alone.
    """
    try:
        with open(SYSTEMS_TSV, encoding="utf-8") as fh:
            for line in fh:
                if line.startswith("#"):
                    continue
                parts = line.rstrip("\n").split("\t")
                if len(parts) == 3:
                    CORES.setdefault(parts[1], parts[2])
    except OSError:
        pass                              # the built-in nine still work


load_systems()


def ensure_core(core):
    """Fetch a core that is not installed yet.

    Installing all 124 systems' cores up front would be several hundred
    megabytes of emulators for consoles nobody here owns. Instead the core
    arrives the first time a game for it does.
    """
    path = os.path.join(COREDIR, core + ".so")
    if os.path.exists(path):
        return True
    url = "%s/%s.so.zip" % (BUILDBOT, core)
    tmp = path + ".zip"
    try:
        os.makedirs(COREDIR, exist_ok=True)
        urllib.request.urlretrieve(url, tmp)
        subprocess.run(["unzip", "-qo", tmp, "-d", COREDIR], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        log("  fetched the %s core" % core)
        return os.path.exists(path)
    except Exception:                     # noqa: BLE001 - any failure is "no core"
        return False
    finally:
        try:
            os.unlink(tmp)
        except OSError:
            pass


# Folders that hold things a system needs but nobody plays. A Dreamcast BIOS
# dropped into the Dreamcast games folder is the obvious case, and it happened:
# six archives appeared on the television and in the guests' game list, between
# Crazy Taxi and Worms Armageddon, as though they were games. Firmware has to
# live somewhere and next to the games it belongs to is a reasonable place to
# put it, so the scan is what should know better.
NOT_GAMES = ("bios", "firmware")


def not_a_game_folder(dirpath):
    """Whether a directory is holding support files rather than games."""
    return any(part.lower() in NOT_GAMES or
               any(word in part.lower() for word in NOT_GAMES)
               for part in dirpath.split(os.sep))


# The data half of a disc image, as opposed to the file you actually launch.
TRACK_EXTS = {"bin", "iso", "img"}
# Files that stand for a whole disc, most specific first.
CUE_EXTS = {"cue", "toc", "ccd"}

